# vulcanai_mcp_viewer.py
#
# Read-only VulcanAI Textual console that shows what the MCP server does with the plans
# Claude sends. It follows the server log file: lines starting with EVENT_MARKER are
# VulcanAI log events (kept in VulcanAI markup), any other line is raw output (ROS logs, prints).
import argparse
import asyncio
import json
import os
import signal
import time
from pathlib import Path

from vulcanai.console.console import VulcanConsole

EVENT_MARKER = "\x1eVULCANAI "


class ClaudeViewerConsole(VulcanConsole):
    DEFAULT_CMD_PLACEHOLDER = "Read-only: send prompts from Claude. Commands: /clear, /exit"

    def __init__(self, log_file: str, server_pid: int):
        super().__init__(model="Claude (MCP)", default_tools=False)
        self.log_file = log_file
        self.server_pid = server_pid
        self.history_index = None
        self.plan_count = 0

    async def bootstrap(self) -> None:
        """Replaces the default bootstrap: no manager or LLM, just follow the server log."""
        self.commands = {"/clear": self.cmd_clear, "/exit": self.cmd_quit}
        self.tab_matches = []
        self.tab_index = 0
        self._update_variables_panel()
        self.is_ready = True
        self.logger.log_console("VulcanAI console connected to the Claude MCP server")
        self.logger.log_console(
            "Plans are generated by Claude. Use <bold>'/exit'</bold> or <bold>'Ctrl+Q'</bold> to quit."
        )
        self.set_input_enabled(True)
        # The MCP server closes this console with SIGTERM: exit cleanly so the terminal closes too
        asyncio.get_running_loop().add_signal_handler(signal.SIGTERM, self.exit)
        asyncio.create_task(self._follow_log())

    def _update_variables_panel(self) -> None:
        self.query_one("#variables").update(
            f" AI model: Claude (MCP)\n Server PID: {self.server_pid}\n"
            f" ROS_DOMAIN_ID = {os.environ.get('ROS_DOMAIN_ID', '0')}\n Plans received: {self.plan_count}"
        )

    async def on_input_submitted(self, event) -> None:
        text = event.value.strip()
        event.input.value = ""
        if text in self.commands:
            self.commands[text](None)
        elif text:
            self.logger.log_console("This console is read-only. Write your prompts in the Claude session.")

    def _handle_event(self, ev: dict) -> None:
        kind = ev.get("type")
        if kind == "log":
            self.add_line(ev["msg"], ev.get("color", ""))
        elif kind == "plan_start":
            self.plan_count += 1
            self.history.append(ev.get("summary") or "(plan from Claude)")
            self._update_history_panel()
            self._update_variables_panel()
            self.hooks.on_request_start("Executing plan from Claude...")
        elif kind == "plan_end":
            self.hooks.on_request_end()

    def _server_alive(self) -> bool:
        try:
            os.kill(self.server_pid, 0)
            return True
        except OSError:
            return False

    async def _follow_log(self) -> None:
        while not os.path.exists(self.log_file):
            await asyncio.sleep(0.1)
        buffer = ""
        last_alive_check = time.monotonic()
        with open(self.log_file, encoding="utf-8", errors="replace") as f:
            while True:
                # Start over if the file was truncated
                if os.path.getsize(self.log_file) < f.tell():
                    f.seek(0)
                    buffer = ""
                chunk = f.read()
                if chunk:
                    buffer += chunk
                    *lines, buffer = buffer.split("\n")
                    for line in lines:
                        if line.startswith(EVENT_MARKER):
                            try:
                                self._handle_event(json.loads(line[len(EVENT_MARKER) :]))
                            except Exception:
                                self.add_line(line)
                        elif line.strip():
                            # Raw output (ROS logs, prints), written as the console does for stdout/stderr
                            self.add_line(line)
                    continue
                if time.monotonic() - last_alive_check > 1.0:
                    last_alive_check = time.monotonic()
                    if not self._server_alive():
                        self.hooks.on_request_end()
                        self.logger.log_msg("MCP server stopped. Press Ctrl+Q to close this window.", error=True)
                        return
                await asyncio.sleep(0.1)


def main() -> None:
    parser = argparse.ArgumentParser(description="VulcanAI console viewer for the Claude MCP server")
    parser.add_argument("log_file")
    parser.add_argument("--pid", type=int, required=True, help="PID of the MCP server")
    args = parser.parse_args()
    ClaudeViewerConsole(str(Path(args.log_file).expanduser().resolve()), args.pid).run_console()


if __name__ == "__main__":
    main()
